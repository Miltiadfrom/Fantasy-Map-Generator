function capitalize(str) {
  return str.charAt(0).toUpperCase() + str.slice(1);
}

function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function genCountry() {
  const prefix = pick(NAME_GEN_DATA.countryPrefixes);
  const core = capitalize(pick(NAME_GEN_DATA.countryCoresA) + pick(NAME_GEN_DATA.countryCoresB));
  return `${prefix} ${core}`;
}

function genCity() {
  return capitalize(pick(NAME_GEN_DATA.cityStems) + pick(NAME_GEN_DATA.cityEndings));
}

